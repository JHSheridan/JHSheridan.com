// Function to initialize the globe
function initializeGlobe() {
    const globeElement = document.getElementById('globeViz');
    if (!globeElement) return;

    // Get location data from data attributes, fallback to default if not available
    const lat = parseFloat(globeElement.dataset.latitude) || 35.5328838;
    const lng = parseFloat(globeElement.dataset.longitude) || -82.8373558;
    
    // Debug logging
    console.log('Globe element dataset:', globeElement.dataset);
    console.log('Parsed coordinates - lat:', lat, 'lng:', lng);
    
    try {
        const globe = Globe()
        .globeImageUrl('//unpkg.com/three-globe/example/img/earth-day.jpg')
        .backgroundColor('rgba(0,0,0,0)')
        .width('225')
        .height('225')
        .ringsData([{
            lat: lat, // Latitude for the ring
            lng: lng, // Longitude for the ring
            maxR: 6, // Maximum radius of the ring
            propagationSpeed: 4, // Speed at which the ring propagates
            repeatPeriod: 650 // Time period for the ring to repeat
        }])
        .ringColor(() => `rgba(255,38,38,0.8)`)
        .ringMaxRadius('maxR')
        .ringPropagationSpeed('propagationSpeed')
        .ringRepeatPeriod('repeatPeriod')
        (globeElement);

        // Point the camera at the location once the scene is mounted.
        // (globe.gl runs its own render loop, so no manual animate loop is
        // needed — and a manual one would override this camera tween.)
        requestAnimationFrame(() => {
            globe.pointOfView({ lat: lat, lng: lng, altitude: 1.7 });
        });

        // Mark as loaded to hide loading state
        globeElement.classList.add('loaded');
    } catch (error) {
        console.error('Error initializing globe:', error);
        // Keep the loading state visible if there's an error
    }
}

// Wait for the globe.gl library to load
let libraryCheckCount = 0;
const maxLibraryChecks = 50; // 5 seconds max wait time

function waitForGlobeLibrary() {
    if (typeof Globe !== 'undefined') {
        initializeGlobe();
    } else if (libraryCheckCount < maxLibraryChecks) {
        libraryCheckCount++;
        // Check again after a short delay
        setTimeout(waitForGlobeLibrary, 100);
    } else {
        console.warn('Globe.gl library failed to load within timeout period');
        // Hide loading state even if library failed to load
        const globeElement = document.getElementById('globeViz');
        if (globeElement) {
            globeElement.classList.add('loaded');
        }
    }
}

// Only initialize globe if the element exists
const globeElement = document.getElementById('globeViz');
if (globeElement) {
    // Start checking for the library
    waitForGlobeLibrary();
}



// Teaser/Nav Link Blinking Functionality
document.addEventListener('DOMContentLoaded', function() {
    const teasers = document.querySelectorAll('.teaser');
    const navLinks = document.querySelectorAll('#full-menu nav a, #mobile-menu nav a');
    let blinkInterval = null;

    // Function to start blinking a nav link
    function startBlinking(navLink) {
        // Stop any existing blink
        stopBlinking();
        
        // Add blink class immediately
        navLink.classList.add('nav-blink');
        
        // Set up interval for continuous blinking
        blinkInterval = setInterval(() => {
            navLink.classList.toggle('nav-blink');
        }, 500); // Blink every 500ms
    }

    // Function to stop blinking
    function stopBlinking() {
        if (blinkInterval) {
            clearInterval(blinkInterval);
            blinkInterval = null;
        }
        // Remove blink class from all nav links
        navLinks.forEach(link => link.classList.remove('nav-blink'));
    }

    // Add hover event listeners to teasers
    teasers.forEach(teaser => {
        const teaserHref = teaser.getAttribute('href');
        
        teaser.addEventListener('mouseenter', function() {
            // Find matching nav link(s)
            const matchingNavLinks = Array.from(navLinks).filter(navLink => 
                navLink.getAttribute('href') === teaserHref
            );
            
            // Start blinking the first matching nav link
            if (matchingNavLinks.length > 0) {
                startBlinking(matchingNavLinks[0]);
            }
        });

        teaser.addEventListener('mouseleave', function() {
            stopBlinking();
        });
    });
});


