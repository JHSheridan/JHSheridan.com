(() => {
  // <stdin>
  console.log("This site was generated by Hugo.");
  function initializeGlobe() {
    const globeElement2 = document.getElementById("globeViz");
    if (!globeElement2) return;
    const lat = parseFloat(globeElement2.dataset.latitude) || 35.5328838;
    const lng = parseFloat(globeElement2.dataset.longitude) || -82.8373558;
    console.log("Globe element dataset:", globeElement2.dataset);
    console.log("Parsed coordinates - lat:", lat, "lng:", lng);
    try {
      let animate2 = function() {
        requestAnimationFrame(animate2);
        globe.controls().update();
        globe.renderer().render(globe.scene(), globe.camera());
      };
      var animate = animate2;
      const globe = Globe().globeImageUrl("//unpkg.com/three-globe/example/img/earth-day.jpg").backgroundColor("rgba(0,0,0,0)").width("225").height("225").pointOfView({ lat, lng, altitude: 1.7 }, 100).ringsData([{
        lat,
        // Latitude for the ring
        lng,
        // Longitude for the ring
        maxR: 6,
        // Maximum radius of the ring
        propagationSpeed: 4,
        // Speed at which the ring propagates
        repeatPeriod: 650
        // Time period for the ring to repeat
      }]).ringColor(() => `rgba(255,38,38,0.8)`).ringMaxRadius("maxR").ringPropagationSpeed("propagationSpeed").ringRepeatPeriod("repeatPeriod")(globeElement2);
      globeElement2.classList.add("loaded");
      animate2();
    } catch (error) {
      console.error("Error initializing globe:", error);
    }
  }
  var libraryCheckCount = 0;
  var maxLibraryChecks = 50;
  function waitForGlobeLibrary() {
    if (typeof Globe !== "undefined") {
      initializeGlobe();
    } else if (libraryCheckCount < maxLibraryChecks) {
      libraryCheckCount++;
      setTimeout(waitForGlobeLibrary, 100);
    } else {
      console.warn("Globe.gl library failed to load within timeout period");
      const globeElement2 = document.getElementById("globeViz");
      if (globeElement2) {
        globeElement2.classList.add("loaded");
      }
    }
  }
  var globeElement = document.getElementById("globeViz");
  if (globeElement) {
    waitForGlobeLibrary();
  }
  document.addEventListener("DOMContentLoaded", function() {
    const teasers = document.querySelectorAll(".teaser");
    const navLinks = document.querySelectorAll("#full-menu nav a, #mobile-menu nav a");
    let blinkInterval = null;
    function startBlinking(navLink) {
      stopBlinking();
      navLink.classList.add("nav-blink");
      blinkInterval = setInterval(() => {
        navLink.classList.toggle("nav-blink");
      }, 500);
    }
    function stopBlinking() {
      if (blinkInterval) {
        clearInterval(blinkInterval);
        blinkInterval = null;
      }
      navLinks.forEach((link) => link.classList.remove("nav-blink"));
    }
    teasers.forEach((teaser) => {
      const teaserHref = teaser.getAttribute("href");
      teaser.addEventListener("mouseenter", function() {
        const matchingNavLinks = Array.from(navLinks).filter(
          (navLink) => navLink.getAttribute("href") === teaserHref
        );
        if (matchingNavLinks.length > 0) {
          startBlinking(matchingNavLinks[0]);
        }
      });
      teaser.addEventListener("mouseleave", function() {
        stopBlinking();
      });
    });
  });
})();
